/** Explicit OpenAPI surface used by release review and drift tests. */
export const RELEASE_OPENAPI_MANIFEST = {
  openapi: "3.0.3",
  paths: RELEASE_ROUTE_MANIFEST.reduce<
    Record<
      string,
      Record<
        string,
        { operationId: string; "x-jobstash-route-state": "active" | "gone" }
      >
    >
  >((paths, [controller, handler, verb, path, state]) => {
    const openApiPath = `/${path.replace(/:([^/]+)/g, "{$1}")}`;
    paths[openApiPath] ??= {};
    paths[openApiPath][verb.toLowerCase()] = {
      operationId: `${controller}_${handler}`,
      "x-jobstash-route-state": state,
    };
    return paths;
  }, {}),
} as const;
